const dict = { en: { ...base.en, ...extra.en }, ha: { ...base.ha, ...extra.ha } };

let lang = 'en';
try { const saved = localStorage.getItem('spk-lang'); if (saved === 'ha' || saved === 'en') lang = saved; } catch {}

export const getLang = () => lang;
export function setLang(l) {
  lang = l === 'ha' ? 'ha' : 'en';
  try { localStorage.setItem('spk-lang', lang); } catch {}
  document.documentElement.lang = lang;
}

// t('key') or t('key', {n: 3}) -> replaces {n}. Unknown keys fall back to English, then to the key.
export function t(key, vars) {
  let s = dict[lang][key] ?? dict.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replace('{' + k + '}', vars[k]);
  return s;
}
